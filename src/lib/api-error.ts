export function apiErrorMessage(data: unknown, fallback = "Something went wrong. Please try again."): string {
  const body = (data && typeof data === "object" ? data : {}) as { error?: unknown; ref?: unknown; message?: unknown };
  const code = typeof body.error === "string" ? body.error : "";
  if (code === "internal_error") {
    return body.ref ? `Something went wrong (ref ${String(body.ref)}). Please try again.` : fallback;
  }
  // A message written to take a detail ("…for:") reads as a sentence when there is none.
  if (code && MESSAGES[code]) return MESSAGES[code].replace(/:$/, ".");
  // Codes can carry a detail after a colon, e.g. "year_has_open_periods:Apr 2026,May 2026".
  const [base, ...rest] = code.split(":");
  const detail = rest.join(":").trim();
  if (base && detail && MESSAGES[base]) {
    const msg = MESSAGES[base];
    return msg.endsWith(":") ? `${msg} ${detail.replace(/,/g, ", ")}.` : `${msg} (${detail})`;
  }
  if (code) return code.replace(/_/g, " ").replace(/^\w/, (c) => c.toUpperCase());
  return fallback;
}
